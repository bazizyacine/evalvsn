#!/usr/bin/env python3
"""LaTeX tables of the revision (study 10), French and English: the controls from
src/data/revision.tsv and the agents' decisions from src/data/agent-trace.tsv. A
value the sets do not provide prints as a dash.

Usage: make_tables_revision.py
"""
import os
from decimal import ROUND_HALF_UP, Decimal

import table_cells

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', 'src')
# The agents' policy in its own column, the stacks in the article's order
# (agents, then hybrid) under each policy: frozen, the constant exploration
# of E0 (epsilon = 0.1), then the decaying exploration; the rule stack, which
# has no agent, first and alone, its policy cell saying so rather than a dash.
# (policy, arm, traced arm, stack)
POLICIES = {'fr': {'': 'sans agent', 'frozen': 'figée', 'const': '$\\varepsilon$ constant', 'edec': '$\\varepsilon$ décroissant'},
            'en': {'': 'no agent', 'frozen': 'frozen', 'const': 'constant $\\varepsilon$', 'edec': 'decaying $\\varepsilon$'}}
ARMS = (('', 'rules', 'rules', 'rules'),
        ('frozen', 'agents-frozen', 'agents-frozen', 'agents'), ('frozen', 'hybrid-frozen', 'hybrid-frozen', 'hybrid'),
        ('const', 'agents', 'agents-tr', 'agents'), ('const', 'hybrid', 'hybrid-tr', 'hybrid'),
        ('edec', 'agents-edec', 'agents-edec', 'agents'), ('edec', 'hybrid-edec', 'hybrid-edec', 'hybrid'))
STACK_NAMES = {'fr': {'rules': 'Règles', 'agents': 'Agents', 'hybrid': 'Hybride'},
               'en': {'rules': 'Rules', 'agents': 'Agents', 'hybrid': 'Hybrid'}}
# Relative widths of the X columns: each holds its header on one line plus an
# equal share of the free width (measured on the MDPI class, 12 Nov 2026).
WIDTHS = ('1.20', '1.40', '1.03', '0.94', '0.74', '0.86', '0.83')
# Images, Decl., RREQ and RERR are defined in the metrics table
# (tab:metriques, Section 2.5): no note under this table (12 Nov 2026).
HEAD = {'fr': ('Politique', 'Pile', 'PSNR (dB)', 'Perte M1 (\\%)', 'Perte (\\%)', 'Images', 'Décl.', 'RREQ', 'RERR'),
        'en': ('Policy', 'Stack', 'PSNR (dB)', 'M1 loss (\\%)', 'Loss (\\%)', 'Images', 'Decl.', 'RREQ', 'RERR')}


AGENTS = (('path', 'hybrid', 'Chemin', 'Path'), ('congestion', 'hybrid', 'Congestion', 'Congestion'),
          ('access', 'hybrid', 'Accès au canal', 'Channel access'), ('discard', 'hybrid', 'Rejet anticipé', 'Early discard'),
          ('discovery', 'hybrid', 'Découverte', 'Discovery'), ('power', 'hybrid', 'Puissance', 'Power'),
          ('break', 'agents', 'Détection de rupture', 'Link-break detection'))
# The last two headers on two lines, the median per node on one.
WIDTHS_AGENTS = ('0.64', '0.80', '1.32', '1.00', '1.24')
# the stack each agent is traced in, in its own column (the hybrid stack, but
# the link-break agent, which only the agents stack holds); the other headers
# are defined in the metrics table (tab:metriques), and the power agent's
# untraced pairs are written out in the cell: no note (12 Nov 2026)
HEAD_AGENTS = {'fr': ('Agent', 'Pile', 'Nœuds', 'Décisions', 'Médiane par nœud', 'Action la plus choisie (\\%)', 'Hors du choix initial (\\%)'),
               'en': ('Agent', 'Stack', 'Nodes', 'Decisions', 'Median per node', 'Most chosen action (\\%)', 'Away from the initial choice (\\%)')}
NOT_TRACED = {'fr': 'non tracé', 'en': 'not traced'}


def cols(widths, stubs=1):
    """Left-aligned stubs, then centered X columns of relative widths."""
    return 'l' * stubs + ''.join('>{\\hsize=%s\\hsize\\centering\\arraybackslash}X' % w for w in widths)


def load(name='revision.tsv'):
    lines = [l for l in open(os.path.join(SRC, 'data', name)) if not l.startswith('#')]
    cols = lines[0].rstrip('\n').split('\t')
    return [dict(zip(cols, l.rstrip('\n').split('\t'))) for l in lines[1:]]


def mean(rows, arm, metric):
    """The mean over the 60 seeds, or None when the sets do not provide all 60."""
    v = [float(r[metric]) for r in rows if r['arm'] == arm and r['split'] == '9M3D' and r['period'] == 'p9' and r[metric] != '']
    return sum(v) / len(v) if len(v) == 60 else None


def num(x, nd, lang):
    if x is None:
        return '--'
    # Half up, as the text rounds: 7.25 prints 7.3.
    s = str(Decimal(repr(x)).quantize(Decimal(1).scaleb(-nd), rounding=ROUND_HALF_UP))
    # Thousands: a thin space in French from four digits, as the French
    # tables do; in English a comma from five digits only, as MDPI asks.
    if nd == 0 and x >= 1000 and lang == 'fr':
        s = s[:-3] + '\\,' + s[-3:]
    elif nd == 0 and x >= 10000:
        s = s[:-3] + ',' + s[-3:]
    return s.replace('.', '{,}') if lang == 'fr' else s


def write(lang, rows):
    out = ['% generated by tools/make_tables_revision.py from src/data/revision.tsv',
           table_cells.setup(lang),
           '\\begin{tabularx}{\\linewidth}{%s}' % cols(WIDTHS, 2), '\\toprule',
           ' & '.join('\\textbf{%s}' % h for h in HEAD[lang]) + ' \\\\', '\\midrule']
    body = []
    for policy, arm, traced, stack in ARMS:
        cells = [num(mean(rows, arm, m), nd, lang) for m, nd in
                 (('psnr', 2), ('m1loss', 1), ('loss', 1), ('usable', 1), ('declared', 1))]
        cells += [num(mean(rows, traced, m), 0, lang) for m in ('rreq_all', 'rerr')]
        body.append([policy, STACK_NAMES[lang][stack]] + cells)
    body = table_cells.align_rows(body, lang, range(2, 9))
    # the policy written once over its stacks, vertically centered; no rule
    # between the stacks of a policy, a \\midrule between two policies
    # (table_cells.rules)
    after = table_cells.rules(r[0] for r in body)
    for i, r in enumerate(body):
        policy = r[0]
        n = sum(1 for x in body if x[0] == policy)
        first = i == 0 or body[i - 1][0] != policy
        label = POLICIES[lang][policy]
        r = [('\\multirow[m]{%d}{*}{%s}' % (n, label) if n > 1 else label) if first else ''] + r[1:]
        out.append(' & '.join(r) + ' \\\\')
        if after[i]:
            out.append(after[i])
    out.append('\\end{tabularx}')
    with open(os.path.join(SRC, 'tables', '%s_revision-controles.tex' % lang), 'w') as f:
        f.write('\n'.join(out) + '\n')


def write_agents(lang, rows):
    out = ['% generated by tools/make_tables_revision.py from src/data/agent-trace.tsv',
           table_cells.setup(lang),
           '\\begin{tabularx}{\\linewidth}{%s}' % cols(WIDTHS_AGENTS, 2), '\\toprule',
           ' & '.join('\\textbf{%s}' % h for h in HEAD_AGENTS[lang]) + ' \\\\', '\\midrule']
    body = []
    for agent, arm, fr, en in AGENTS:
        r = next(x for x in rows if x['arm'] == arm and x['agent'] == agent and x['t'] == '999')
        top = 100.0 * max(float(r['a%d' % a]) for a in range(9)) / float(r['decisions'])
        cells = [num(float(r['nodes']), 0, lang), num(float(r['decisions']), 0, lang), num(float(r['median']), 0, lang),
                 num(top, 1, lang), num(float(r['changed']), 1, lang) if r['changed'] else NOT_TRACED[lang]]
        body.append([fr if lang == 'fr' else en, STACK_NAMES[lang][arm]] + cells)
    body = table_cells.align_rows(body, lang, range(2, 7))
    for i, r in enumerate(body):
        out.append(' & '.join(r) + ' \\\\')
        out.append('\\bottomrule' if i == len(body) - 1 else '\\midrule')
    out.append('\\end{tabularx}')
    with open(os.path.join(SRC, 'tables', '%s_revision-agents.tex' % lang), 'w') as f:
        f.write('\n'.join(out) + '\n')


def main():
    rows, agents = load(), load('agent-trace.tsv')
    for lang in ('fr', 'en'):
        write(lang, rows)
        write_agents(lang, agents)
    print('tables/{fr,en}_revision-{controles,agents}.tex')


if __name__ == '__main__':
    main()
