#!/usr/bin/env python3
"""LaTeX tables of the revision (study 10), French and English: the controls from
src/data/revision.tsv and the agents' decisions from src/data/agent-trace.tsv. A
value the sets do not provide prints as a dash.

Usage: make_tables_revision.py
"""
import os
from decimal import ROUND_HALF_UP, Decimal

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', 'src')
ARMS = (('rules', 'rules', 'Règles', 'Rules'),
        ('hybrid-frozen', 'hybrid-frozen', 'Hybride, figée', 'Hybrid, frozen'),
        ('agents-frozen', 'agents-frozen', 'Agents, figée', 'Agents, frozen'),
        ('hybrid', 'hybrid-tr', 'Hybride', 'Hybrid'),
        ('agents', 'agents-tr', 'Agents', 'Agents'),
        ('hybrid-edec', 'hybrid-edec', 'Hybride, $\\varepsilon$ décroissant', 'Hybrid, decaying $\\varepsilon$'),
        ('agents-edec', 'agents-edec', 'Agents, $\\varepsilon$ décroissant', 'Agents, decaying $\\varepsilon$'))
HEAD = {'fr': ('Pile', 'PSNR (dB)', 'Perte M1 (\\%)', 'Perte (\\%)', 'Images\\textsuperscript{1}', 'Décl.\\textsuperscript{2}', 'RREQ\\textsuperscript{3}', 'RERR\\textsuperscript{3}'),
        'en': ('Stack', 'PSNR (dB)', 'M1 loss (\\%)', 'Loss (\\%)', 'Images\\textsuperscript{1}', 'Decl.\\textsuperscript{2}', 'RREQ\\textsuperscript{3}', 'RERR\\textsuperscript{3}')}


AGENTS = (('path', 'hybrid', 'Chemin', 'Path'), ('congestion', 'hybrid', 'Congestion', 'Congestion'),
          ('access', 'hybrid', 'Accès au canal', 'Channel access'), ('discard', 'hybrid', 'Rejet anticipé', 'Early discard'),
          ('discovery', 'hybrid', 'Découverte', 'Discovery'), ('power', 'hybrid', 'Puissance', 'Power'),
          ('break', 'agents', 'Détection de rupture', 'Link-break detection'))
HEAD_AGENTS = {'fr': ('Agent\\textsuperscript{1}', 'Nœuds\\textsuperscript{2}', 'Décisions\\textsuperscript{3}', 'Médiane par nœud', 'Action la plus choisie (\\%)', 'Hors du choix initial (\\%)\\textsuperscript{4}'),
               'en': ('Agent\\textsuperscript{1}', 'Nodes\\textsuperscript{2}', 'Decisions\\textsuperscript{3}', 'Median per node', 'Most chosen action (\\%)', 'Away from the initial choice (\\%)\\textsuperscript{4}')}


def load(name='revision.tsv'):
    lines = [l for l in open(os.path.join(SRC, 'data', name)) if not l.startswith('#')]
    cols = lines[0].rstrip('\n').split('\t')
    return [dict(zip(cols, l.rstrip('\n').split('\t'))) for l in lines[1:]]


def mean(rows, arm, metric):
    """The mean over the 60 seeds, or None when the sets do not provide all 60."""
    v = [float(r[metric]) for r in rows if r['arm'] == arm and r['split'] == '9M3D' and r['period'] == 'p9' and r[metric] != '']
    return sum(v) / len(v) if len(v) == 60 else None


def num(x, nd, lang):
    if x is None:
        return '--'
    # Half up, as the text rounds: 7.25 prints 7.3.
    s = str(Decimal(repr(x)).quantize(Decimal(1).scaleb(-nd), rounding=ROUND_HALF_UP))
    # Thousands: a thin space in French from four digits, as the French
    # tables do; in English a comma from five digits only, as MDPI asks.
    if nd == 0 and x >= 1000 and lang == 'fr':
        s = s[:-3] + '\\,' + s[-3:]
    elif nd == 0 and x >= 10000:
        s = s[:-3] + ',' + s[-3:]
    return s.replace('.', '{,}') if lang == 'fr' else s


def write(lang, rows):
    out = ['% generated by tools/make_tables_revision.py from src/data/revision.tsv',
           '\\begin{tabularx}{\\linewidth}{lCCCCCCC}', '\\toprule',
           ' & '.join('\\textbf{%s}' % h for h in HEAD[lang]) + ' \\\\', '\\midrule']
    for i, (arm, traced, fr, en) in enumerate(ARMS):
        cells = [num(mean(rows, arm, m), nd, lang) for m, nd in
                 (('psnr', 2), ('m1loss', 1), ('loss', 1), ('usable', 1), ('declared', 1))]
        cells += [num(mean(rows, traced, m), 0, lang) for m in ('rreq_all', 'rerr')]
        out.append(' & '.join([fr if lang == 'fr' else en] + cells) + ' \\\\')
        out.append('\\bottomrule' if i == len(ARMS) - 1 else '\\midrule')
    out.append('\\end{tabularx}')
    with open(os.path.join(SRC, 'tables', '%s_revision-controles.tex' % lang), 'w') as f:
        f.write('\n'.join(out) + '\n')


def write_agents(lang, rows):
    out = ['% generated by tools/make_tables_revision.py from src/data/agent-trace.tsv',
           '\\begin{tabularx}{\\linewidth}{lCCCCC}', '\\toprule',
           ' & '.join('\\textbf{%s}' % h for h in HEAD_AGENTS[lang]) + ' \\\\', '\\midrule']
    for i, (agent, arm, fr, en) in enumerate(AGENTS):
        r = next(x for x in rows if x['arm'] == arm and x['agent'] == agent and x['t'] == '999')
        top = 100.0 * max(float(r['a%d' % a]) for a in range(9)) / float(r['decisions'])
        cells = [num(float(r['nodes']), 0, lang), num(float(r['decisions']), 0, lang), num(float(r['median']), 0, lang),
                 num(top, 1, lang), num(float(r['changed']), 1, lang) if r['changed'] else '--\\textsuperscript{5}']
        out.append(' & '.join([fr if lang == 'fr' else en] + cells) + ' \\\\')
        out.append('\\bottomrule' if i == len(AGENTS) - 1 else '\\midrule')
    out.append('\\end{tabularx}')
    with open(os.path.join(SRC, 'tables', '%s_revision-agents.tex' % lang), 'w') as f:
        f.write('\n'.join(out) + '\n')


def main():
    rows, agents = load(), load('agent-trace.tsv')
    for lang in ('fr', 'en'):
        write(lang, rows)
        write_agents(lang, agents)
    print('tables/{fr,en}_revision-{controles,agents}.tex')


if __name__ == '__main__':
    main()
