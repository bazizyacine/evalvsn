#!/usr/bin/env python3
"""LaTeX table of the generalisation of the revision (study 10, tranche T5,
experiment E5, scenario series), French and English, from src/data/revision.tsv through
analyse_generalisation.py.

One row for the reference scenario, then one per variant, at GOP 9-3 and
T = 9 s: the rule stack's packet loss, the PSNR of the four stacks (means over
the 60 seeds), then the gaps over the rules, per-seed differences, the same
three under each: hybrid - rules and agents - rules (PSNR with its p, Holm over
the five variants; usable images). The reference row's p is a single test. A cell that the 60 seeds do not all
back prints as a dash.

Usage: python3 tools/make_tables_generalisation.py [OUT_DIR]   (default: src/tables)
"""
import os
import sys
from decimal import ROUND_HALF_UP, Decimal

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import analyse_generalisation as an  # noqa: E402
import table_cells  # noqa: E402

ROWS = ((None, 'Référence', 'Reference'),
        ('forest', 'Vidéo forêt', 'Forest video'),
        ('smoke', 'Vidéo fumée', 'Smoke video'),
        ('j8', 'Grille de \\SI{30}{\\metre}', '\\SI{30}{\\metre} grid'),
        ('swap', 'Caméra et puits échangés', 'Camera and sink swapped'),
        ('v15', 'Vitesse de tête $\\times 1{,}5$', 'Head spread rate $\\times 1.5$'))
# The four stacks in the article's order, then the two gaps over the rules,
# each under its own group named as in the other tables of differences.
STACKS = ('pq', 'rules', 'agents', 'hybrid')
GROUPS = {'fr': ('PSNR (dB)', 'Hybride $-$ Règles', 'Agents $-$ Règles'),
          'en': ('PSNR (dB)', 'Hybrid $-$ Rules', 'Agents $-$ Rules')}
# The loss is the rule stack's: the stack heads its column on the row of the
# groups; Images is defined in the metrics table (tab:metriques) and the
# reference scenario in the caption: no note under this table (12 Nov 2026).
LOSS_STACK = {'fr': 'Règles', 'en': 'Rules'}
HEAD = {'fr': ('Variante', 'Perte (\\%)', 'AOMDV', 'Règles', 'Agents', 'Hybride',
               'PSNR (dB)', '$p$', 'Images', 'PSNR (dB)', '$p$', 'Images'),
        'en': ('Variant', 'Loss (\\%)', 'AOMDV', 'Rules', 'Agents', 'Hybrid',
               'PSNR (dB)', '$p$', 'Images', 'PSNR (dB)', '$p$', 'Images')}
# Relative widths of the eleven X columns after the variant (they sum to 11),
# for 9 pt type and 4 pt between columns: every variant on one line, the loss
# and the gap headers on two lines, the bold stack names and "< 0,001" on one;
# each column holds its widest line plus an equal share of the free width,
# about 0.01 of a unit once the agents' images are in (measured on the MDPI
# class, 12 Nov 2026: "AOMDV" 38.0 pt bold, "Images" 33.5 pt, "< 0,001"
# 30.3 pt, one unit about 30 pt). On 12 Nov 2026 the rule stack's name went
# above the loss column ("Règles" 27 pt bold): 3.5 pt between columns instead
# of 4 pt frees the width it needs, about 31 pt a unit.
WIDTHS = ('0.88', '1.24', '0.92', '0.95', '1.13', '0.84', '1.00', '1.10', '0.84', '1.00', '1.10')


def rounded(x, nd):
    # Half up, as the text rounds: 0.125 prints 0.13.
    return Decimal(repr(x)).quantize(Decimal(1).scaleb(-nd), rounding=ROUND_HALF_UP)


def plain(x, nd, lang):
    if x is None:
        return '--'
    s = str(rounded(x, nd))
    return s.replace('.', '{,}') if lang == 'fr' else s


def signed(x, nd, lang):
    if x is None:
        return '--'
    d = rounded(x, nd)
    s = str(abs(d))
    s = s.replace('.', '{,}') if lang == 'fr' else s
    if d == 0:
        return s
    return ('+' if d > 0 else '$-$') + s


def pval(p, lang):
    if p is None:
        return '--'
    if p < 0.001:
        return '$< 0{,}001$' if lang == 'fr' else '$< 0.001$'
    s = str(rounded(p, 3))
    return s.replace('.', '{,}') if lang == 'fr' else s


def gap(res, contrast, v, metric):
    """(mean, p) of a contrast under variant v: Holm over the five variants, a
    single test for the reference."""
    t = res['reference'][contrast][metric] if v is None else res['families']['gap'][contrast][metric][v]
    if t is None:
        return None, None
    return t['mean'], (t['p'] if v is None else t['holm'])


def write(lang, res, out_dir):
    g1, g2, g3 = GROUPS[lang]
    assert set(STACKS) == set(an.STACKS)
    cols = 'l' + ''.join('>{\\hsize=%s\\hsize\\centering\\arraybackslash}X' % w for w in WIDTHS)
    # Eleven columns: 9 pt type and 3.5 pt between
    # columns instead of 6 pt, local to the table float (pdflatex, 10 to
    # 12 Nov 2026).
    out = ['% generated by make_tables_generalisation.py from src/data/revision.tsv',
           table_cells.setup(lang), '\\small', '\\setlength{\\tabcolsep}{3.5pt}',
           '\\begin{tabularx}{\\linewidth}{%s}' % cols, '\\toprule',
           ' & \\textbf{%s} & \\multicolumn{4}{c}{\\textbf{%s}} & \\multicolumn{3}{c}{\\textbf{%s}}'
           ' & \\multicolumn{3}{c}{\\textbf{%s}} \\\\' % (LOSS_STACK[lang], g1, g2, g3),
           '\\cmidrule(lr){2-2}\\cmidrule(lr){3-6}\\cmidrule(lr){7-9}\\cmidrule(lr){10-12}',
           ' & '.join('\\textbf{%s}' % h for h in HEAD[lang]) + ' \\\\', '\\midrule']
    body = []
    for i, (v, fr, en) in enumerate(ROWS):
        m = res['means']
        hr, hp = gap(res, 'hybrid-rules', v, 'psnr')
        ar, ap = gap(res, 'agents-rules', v, 'psnr')
        cells = [fr if lang == 'fr' else en, plain(m[an.arm('rules', v)]['loss'], 1, lang)]
        cells += [plain(m[an.arm(s, v)]['psnr'], 2, lang) for s in STACKS]
        cells += [signed(hr, 2, lang), pval(hp, lang), signed(gap(res, 'hybrid-rules', v, 'usable')[0], 1, lang),
                  signed(ar, 2, lang), pval(ap, lang), signed(gap(res, 'agents-rules', v, 'usable')[0], 1, lang)]
        body.append(cells)
    # the numbers of each column aligned on the decimal marker
    body = table_cells.align_rows(body, lang, range(1, 12), pcols=(7, 10))
    for i, cells in enumerate(body):
        out.append(' & '.join(cells) + ' \\\\')
        out.append('\\bottomrule' if i == len(body) - 1 else '\\midrule')
    out.append('\\end{tabularx}')
    path = os.path.join(out_dir, '%s_revision-generalisation.tex' % lang)
    with open(path, 'w') as f:
        f.write('\n'.join(out) + '\n')
    return path


def main():
    out_dir = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, '..', 'src', 'tables')
    res = an.compute()
    for lang in ('fr', 'en'):
        print(write(lang, res, out_dir))


if __name__ == '__main__':
    main()
