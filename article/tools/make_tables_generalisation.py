#!/usr/bin/env python3
"""LaTeX table of the generalisation of the revision (study 10, tranche T5,
experiment E5, scenario series), French and English, from src/data/revision.tsv through
analyse_generalisation.py.

One row for the reference scenario, then one per variant, at GOP 9-3 and
T = 9 s: the rule stack's packet loss, the PSNR of the four stacks (means over
the 60 seeds), then the gaps over the rules, per-seed differences: hybrid -
rules (PSNR with its p, Holm over the five variants; usable images) and agents -
rules (PSNR with its p). The reference row's p is a single test. A cell that the 60 seeds do not all
back prints as a dash.

Usage: python3 tools/make_tables_generalisation.py [OUT_DIR]   (default: src/tables)
"""
import os
import sys
from decimal import ROUND_HALF_UP, Decimal

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import analyse_generalisation as an  # noqa: E402

ROWS = ((None, 'Référence\\textsuperscript{3}', 'Reference\\textsuperscript{3}'),
        ('forest', 'Vidéo forêt', 'Forest video'),
        ('smoke', 'Vidéo fumée', 'Smoke video'),
        ('j8', 'Grille de \\SI{30}{\\metre}', '\\SI{30}{\\metre} grid'),
        ('swap', 'Caméra et puits échangés', 'Camera and sink swapped'),
        ('v15', 'Vitesse de tête $\\times 1{,}5$', 'Head spread rate $\\times 1.5$'))
GROUPS = {'fr': ('PSNR (dB)', 'Pile hybride moins règles'),
          'en': ('PSNR (dB)', 'Hybrid stack minus rules')}
HEAD = {'fr': ('Variante', 'Perte des règles (\\%)\\textsuperscript{1}', 'AOMDV', 'Règles', 'Hybride', 'Agents',
               'Hybride (dB)', '$p$', 'Images\\textsuperscript{2}', 'Agents (dB)', '$p$'),
        'en': ('Variant', 'Rules loss (\\%)\\textsuperscript{1}', 'AOMDV', 'Rules', 'Hybrid', 'Agents',
               'Hybrid (dB)', '$p$', 'Images\\textsuperscript{2}', 'Agents (dB)', '$p$')}
# Relative widths of the eleven X columns (they sum to 11), for 9 pt type:
# the variant on one line but "Caméra et puits échangés", the loss header on
# two, the bold stack names and "< 0,001" on one (measured on the MDPI class,
# 11 Nov 2026).
WIDTHS = ('1.94', '1.22', '1.03', '0.76', '0.94', '0.8', '0.94', '0.83', '0.91', '0.8', '0.83')


def rounded(x, nd):
    # Half up, as the text rounds: 0.125 prints 0.13.
    return Decimal(repr(x)).quantize(Decimal(1).scaleb(-nd), rounding=ROUND_HALF_UP)


def plain(x, nd, lang):
    if x is None:
        return '--'
    s = str(rounded(x, nd))
    return s.replace('.', '{,}') if lang == 'fr' else s


def signed(x, nd, lang):
    if x is None:
        return '--'
    d = rounded(x, nd)
    s = str(abs(d))
    s = s.replace('.', '{,}') if lang == 'fr' else s
    if d == 0:
        return s
    return ('+' if d > 0 else '$-$') + s


def pval(p, lang):
    if p is None:
        return '--'
    if p < 0.001:
        return '$< 0{,}001$' if lang == 'fr' else '$< 0.001$'
    s = str(rounded(p, 3))
    return s.replace('.', '{,}') if lang == 'fr' else s


def gap(res, contrast, v, metric):
    """(mean, p) of a contrast under variant v: Holm over the five variants, a
    single test for the reference."""
    t = res['reference'][contrast][metric] if v is None else res['families']['gap'][contrast][metric][v]
    if t is None:
        return None, None
    return t['mean'], (t['p'] if v is None else t['holm'])


def write(lang, res, out_dir):
    g1, g2 = GROUPS[lang]
    cols = ''.join('>{\\hsize=%s\\hsize%s\\arraybackslash}X' % (w, '\\raggedright' if i == 0 else '\\centering')
                   for i, w in enumerate(WIDTHS))
    # Eleven columns and the footnote markers: 9 pt type and 5 pt between
    # columns instead of 6 pt, local to the table float (pdflatex, 10 and
    # 11 Nov 2026).
    out = ['% generated by make_tables_generalisation.py from src/data/revision.tsv',
           '\\small', '\\setlength{\\tabcolsep}{5pt}',
           '\\begin{tabularx}{\\linewidth}{%s}' % cols, '\\toprule',
           ' & & \\multicolumn{4}{c}{\\textbf{%s}} & \\multicolumn{5}{c}{\\textbf{%s}} \\\\' % (g1, g2),
           '\\cmidrule(lr){3-6}\\cmidrule(lr){7-11}',
           ' & '.join('\\textbf{%s}' % h for h in HEAD[lang]) + ' \\\\', '\\midrule']
    for i, (v, fr, en) in enumerate(ROWS):
        m = res['means']
        hr, hp = gap(res, 'hybrid-rules', v, 'psnr')
        ar, ap = gap(res, 'agents-rules', v, 'psnr')
        cells = [fr if lang == 'fr' else en, plain(m[an.arm('rules', v)]['loss'], 1, lang)]
        cells += [plain(m[an.arm(s, v)]['psnr'], 2, lang) for s in an.STACKS]
        cells += [signed(hr, 2, lang), pval(hp, lang), signed(gap(res, 'hybrid-rules', v, 'usable')[0], 1, lang),
                  signed(ar, 2, lang), pval(ap, lang)]
        out.append(' & '.join(cells) + ' \\\\')
        out.append('\\bottomrule' if i == len(ROWS) - 1 else '\\midrule')
    out.append('\\end{tabularx}')
    path = os.path.join(out_dir, '%s_revision-generalisation.tex' % lang)
    with open(path, 'w') as f:
        f.write('\n'.join(out) + '\n')
    return path


def main():
    out_dir = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, '..', 'src', 'tables')
    res = an.compute()
    for lang in ('fr', 'en'):
        print(write(lang, res, out_dir))


if __name__ == '__main__':
    main()
