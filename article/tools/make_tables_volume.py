#!/usr/bin/env python3
"""Table of video coding (study 10, tranches T3 and T10; experiment E4, decisions d83 and d84),
French and English, from src/data/revision.tsv. At the quality coefficient
0.01, the four stacks in the article's order: the rules and hybrid stacks at
the three GOPs at T = 9 s, and the GOPs 6-6 and 3-9 again at the mean packet
rate of GOP 9-3 (T = 9.32 and 9.65 s); AOMDV and the agents stack at GOP 9-3
and T = 9 s only. Then the four stacks at GOP 9-3 and T = 9 s with the
coefficient 0.1 (arms -q01), whose GOP cell carries note 4: every stack has its
row at both coefficients. Means over the 60 seeds; a cell without all 60 prints
as a dash.

Usage: python3 tools/make_tables_volume.py [out_dir]   (default: src/tables)
"""
import os
import sys
from decimal import ROUND_HALF_UP, Decimal

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', 'src')
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(SRC, 'tables')
# Packets the camera sends per video (the methods' Protocol; the
# lines of each set's encoding/st-priority.dat) and the capture period of each
# set (sets.conf, capture column period:ipt:detect).
PACKETS = {'9M3D': 5352, '6M6D': 5544, '3M9D': 5738}
# At the quality coefficient 0.1, GOP 9-3: the lines of its sets' encoding/st-priority.dat.
PACKETS_Q01 = 2670
PERIOD = {'p9': 9.0, 'p9r32': 9.32, 'p9r65': 9.65}
GOP = {'9M3D': '9-3', '6M6D': '6-6', '3M9D': '3-9'}
ROWS = (('9M3D', 'p9'), ('6M6D', 'p9'), ('6M6D', 'p9r32'), ('3M9D', 'p9'), ('3M9D', 'p9r65'))
ARMS = (('pq', 'AOMDV', 'AOMDV', ROWS[:1]), ('rules', 'Règles', 'Rules', ROWS),
        ('agents', 'Agents', 'Agents', ROWS[:1]), ('hybrid', 'Hybride', 'Hybrid', ROWS))
Q01 = (('pq', 'AOMDV', 'AOMDV'), ('rules', 'Règles', 'Rules'), ('agents', 'Agents', 'Agents'), ('hybrid', 'Hybride', 'Hybrid'))
HEAD = {'fr': ('Pile', 'GOP', '$T$ (s)\\textsuperscript{1}', 'Débit (paquets/s)\\textsuperscript{2}', 'PSNR (dB)', 'Perte M1 (\\%)', 'Perte (\\%)', 'Images\\textsuperscript{3}'),
        'en': ('Stack', 'GOP', '$T$ (s)\\textsuperscript{1}', 'Rate (packets/s)\\textsuperscript{2}', 'PSNR (dB)', 'M1 loss (\\%)', 'Loss (\\%)', 'Images\\textsuperscript{3}')}


def load():
    lines = [l for l in open(os.path.join(SRC, 'data', 'revision.tsv')) if not l.startswith('#')]
    cols = lines[0].rstrip('\n').split('\t')
    return [dict(zip(cols, l.rstrip('\n').split('\t'))) for l in lines[1:]]


def mean(rows, arm, split, period, metric):
    v = [float(r[metric]) for r in rows if r['arm'] == arm and r['split'] == split
         and r['period'] == period and r['dist'] == '40' and r[metric] != '']
    return sum(v) / len(v) if len(v) == 60 else None


def num(x, nd, lang):
    if x is None:
        return '--'
    s = str(Decimal(repr(x)).quantize(Decimal(1).scaleb(-nd), rounding=ROUND_HALF_UP))
    return s.replace('.', '{,}') if lang == 'fr' else s


def write(lang, rows):
    out = ['% generated by tools/make_tables_volume.py from src/data/revision.tsv',
           '\\begin{tabularx}{\\linewidth}{llCCCCCC}', '\\toprule',
           ' & '.join('\\textbf{%s}' % h for h in HEAD[lang]) + ' \\\\', '\\midrule']
    lines = [(a[:3], s, p, '') for a in ARMS for s, p in a[3]] + [(a, '9M3D', 'p9', '-q01') for a in Q01]
    for i, ((arm, fr, en), split, period, suffix) in enumerate(lines):
        T = PERIOD[period]
        packets = PACKETS_Q01 if suffix else PACKETS[split]
        cells = [fr if lang == 'fr' else en, GOP[split] + ('\\textsuperscript{4}' if suffix else ''),
                 num(T, 2 if T != 9.0 else 0, lang), num(packets / (12 * T), 1, lang)]
        cells += [num(mean(rows, arm + suffix, split, period, m), nd, lang)
                  for m, nd in (('psnr', 2), ('m1loss', 1), ('loss', 1), ('usable', 1))]
        out.append(' & '.join(cells) + ' \\\\')
        out.append('\\bottomrule' if i == len(lines) - 1 else '\\midrule')
    out.append('\\end{tabularx}')
    path = os.path.join(OUT, '%s_revision-volume.tex' % lang)
    with open(path, 'w') as f:
        f.write('\n'.join(out) + '\n')
    return path


def main():
    rows = load()
    for lang in ('fr', 'en'):
        print(write(lang, rows))


if __name__ == '__main__':
    main()
