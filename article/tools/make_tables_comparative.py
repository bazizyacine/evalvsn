#!/usr/bin/env python3
"""Generate the comparative study's tables (study 09) from
src/data/comparative.tsv into src/tables/<lang>_comparatif-*.tex (fr: decimal
comma; en: decimal point; both editions by default): the PSNR of the four
stacks per fire and GOP,
with the half-width of the 95 % confidence interval of each mean, the
global and M1 losses, the paired differences between the cross-layer stacks
(Holm over the nine cells of each comparison) and the three-way ANOVA."""
import argparse
import os

import analyse_comparative
from analyse_comparative import anova, load, paired, stats

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'src', 'tables')
FIRES = ('F1', 'F2', 'F3')
SPLITS = (('3M9D', '3-9'), ('6M6D', '6-6'), ('9M3D', '9-3'))
HEAD = '% generated by tools/make_tables_comparative.py from src/data/comparative.tsv\n'
# The words of each edition; the stack and term names follow the vocabulary
# of the writing skill (rule stack, agents stack, hybrid stack).
WORDS = {
    'fr': {'stacks': (('aomdv', 'AOMDV'), ('rules', 'Règles'), ('agents', 'Agents'), ('hybrid', 'Hybride')),
           'pairs': (('hybrid', 'rules', 'Hybride $-$ règles'), ('agents', 'rules', 'Agents $-$ règles'),
                     ('hybrid', 'agents', 'Hybride $-$ agents')),
           'terms': {'stack': 'Pile', 'fire': 'Feu', 'split': 'GOP'},
           'fire': 'Feu', 'factor': 'Facteur', 'df': 'ddl', 'resid': 'Résidus', 'dec': '{,}'},
    'en': {'stacks': (('aomdv', 'AOMDV'), ('rules', 'Rules'), ('agents', 'Agents'), ('hybrid', 'Hybrid')),
           'pairs': (('hybrid', 'rules', 'Hybrid $-$ rules'), ('agents', 'rules', 'Agents $-$ rules'),
                     ('hybrid', 'agents', 'Hybrid $-$ agents')),
           'terms': {'stack': 'Stack', 'fire': 'Fire', 'split': 'GOP'},
           'fire': 'Fire', 'factor': 'Factor', 'df': 'df', 'resid': 'Residuals', 'dec': '.'},
}
W = WORDS['fr']
STACKS = W['stacks']
PAIRS = W['pairs']


def fr(x, nd=1):
    """A number in the current edition's notation (the name stays from the
    French-only version)."""
    return ('%.*f' % (nd, x)).replace('.', W['dec']).replace('-', '$-$')


def pfr(p):
    return ('$< 0%s001$' % W['dec']) if p < 0.001 else fr(p, 3)


def cells(rows, metric):
    out = {}
    for r in rows:
        out.setdefault((r['fire'], r['split'], r['stack']), {})[r['real']] = float(r[metric])
    return out


def first(fire, k):
    """The first column as the MDPI template writes it: the value once,
    vertically centered on the rows it spans."""
    return '\\multirow[m]{%d}{*}{%s}' % (len(SPLITS), fire) if k == 0 else ''


def mean(d):
    return sum(d.values()) / len(d)


def half_ci(d):
    """Half-width of the 95 % confidence interval of the mean (Student)."""
    n = len(d)
    m = mean(d)
    sd = (sum((x - m) ** 2 for x in d.values()) / (n - 1)) ** 0.5
    return stats.t_quantile(0.975, n - 1) * sd / n ** 0.5


def main():
    global W, STACKS, PAIRS
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--lang', choices=('fr', 'en', 'both'), default='both')
    args = ap.parse_args()
    rows = load()
    for lang in (('fr', 'en') if args.lang == 'both' else (args.lang,)):
        W = WORDS[lang]
        STACKS, PAIRS = W['stacks'], W['pairs']
        write(lang, rows)


def write(lang, rows):
    psnr, loss, m1 = cells(rows, 'psnr'), cells(rows, 'loss'), cells(rows, 'm1loss')
    os.makedirs(OUT, exist_ok=True)

    with open(os.path.join(OUT, lang + '_comparatif-psnr.tex'), 'w') as f:
        f.write(HEAD + '\\begin{tabularx}{\\linewidth}{CCCCCC}\n\\toprule\n')
        f.write('\\textbf{%s} & \\textbf{GOP} & ' % W['fire'] + ' & '.join('\\textbf{%s}' % lab for _, lab in STACKS) + ' \\\\\n')
        for fire in FIRES:
            f.write('\\midrule\n')
            for k, (sp, lab) in enumerate(SPLITS):
                vals = [psnr.get((fire, sp, st)) for st, _ in STACKS]
                txt = []
                for v in vals:
                    if not v:
                        txt.append('--')
                    else:
                        txt.append('%s $\\pm$ %s' % (fr(mean(v)), fr(half_ci(v))))
                f.write('%s & %s & %s \\\\\n' % (first(fire, k), lab, ' & '.join(txt)))
        f.write('\\bottomrule\n\\end{tabularx}\n')

    with open(os.path.join(OUT, lang + '_comparatif-pertes.tex'), 'w') as f:
        f.write(HEAD + '\\begin{tabularx}{\\linewidth}{CCCCCC}\n\\toprule\n')
        f.write('\\textbf{%s} & \\textbf{GOP} & ' % W['fire'] + ' & '.join('\\textbf{%s}' % lab for _, lab in STACKS) + ' \\\\\n')
        for fire in FIRES:
            f.write('\\midrule\n')
            for k, (sp, lab) in enumerate(SPLITS):
                txt = []
                for st, _ in STACKS:
                    a, b = loss.get((fire, sp, st)), m1.get((fire, sp, st))
                    txt.append('%s / %s' % (fr(mean(a)), fr(mean(b))) if a and b else '--')
                f.write('%s & %s & %s \\\\\n' % (first(fire, k), lab, ' & '.join(txt)))
        f.write('\\bottomrule\n\\end{tabularx}\n')

    with open(os.path.join(OUT, lang + '_comparatif-tests.tex'), 'w') as f:
        f.write(HEAD + '\\begin{tabularx}{\\linewidth}{CCCCCCCC}\n\\toprule\n')
        f.write('& & ' + ' & '.join('\\multicolumn{2}{c}{\\textbf{%s}}' % lab for _, _, lab in PAIRS) + ' \\\\\n')
        f.write('\\textbf{%s} & \\textbf{GOP} & ' % W['fire'] + ' & '.join(['$\\Delta$ (dB) & $p$'] * len(PAIRS)) + ' \\\\\n')
        adj = {}
        for a, b, _ in PAIRS:
            tests = [((fi, sp), paired(psnr[(fi, sp, a)], psnr[(fi, sp, b)]))
                     for fi in FIRES for sp, _ in SPLITS if (fi, sp, a) in psnr and (fi, sp, b) in psnr]
            holm = stats.holm([(key, None, res[1]) for key, res in tests])
            for (key, res), (_, _, _, pa) in zip(tests, holm):
                adj[(a, b, key)] = (res[0], pa)
        for fire in FIRES:
            f.write('\\midrule\n')
            for k, (sp, lab) in enumerate(SPLITS):
                txt = []
                for a, b, _ in PAIRS:
                    r = adj.get((a, b, (fire, sp)))
                    txt += [('+' if r[0] >= 0 else '') + fr(r[0], 2), pfr(r[1])] if r else ['--', '--']
                f.write('%s & %s & %s \\\\\n' % (first(fire, k), lab, ' & '.join(txt)))
        f.write('\\bottomrule\n\\end{tabularx}\n')

    complete = all((fi, sp, st) in psnr for fi in FIRES for sp, _ in SPLITS for st, _ in STACKS)
    if complete:
        # Among the three cross-layer stacks only: the learning's share;
        # the gap to AOMDV is given by the paired tests.
        analyse_comparative.STACKS = ('rules', 'agents', 'hybrid')
        res, dfe = anova([r for r in rows if r['stack'] != 'aomdv'], 'psnr')
        with open(os.path.join(OUT, lang + '_comparatif-anova.tex'), 'w') as f:
            f.write(HEAD + '\\begin{tabularx}{\\linewidth}{CCCCC}\n\\toprule\n')
            f.write('\\textbf{%s} & \\textbf{%s} & ' % (W['factor'], W['df']) + '\\textbf{$F$} & \\textbf{$p$} & \\textbf{$\\eta^2_p$} \\\\\n\\midrule\n')
            for term, ss, df, F, p, eta in res:
                name = ' $\\times$ '.join(W['terms'][t.strip()] for t in term.split(' x '))
                f.write('%s & %d & %s & %s & %s \\\\\n\\midrule\n' % (name, df, fr(F, 1), pfr(p), fr(eta, 2)))
            f.write('%s & %d & & & \\\\\n\\bottomrule\n\\end{tabularx}\n' % (W['resid'], dfe))
    print('tables written to', os.path.relpath(OUT), '' if complete else '(ANOVA waits for the complete design)')


if __name__ == '__main__':
    main()
