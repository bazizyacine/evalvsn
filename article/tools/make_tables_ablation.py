#!/usr/bin/env python3
"""LaTeX table of the single-agent ablations of the revision (study 10, experiment E2),
French and English, from src/data/revision.tsv through tools/analyse_ablation.py.

One row per agent. Each cell is the mean over the 60 seeds of the per-seed
difference between the stack with the agent and the same stack with its rule:
alone on the rule stack (rules-only<X> - rules), and in the hybrid stack
(hybrid - hybrid-no<X>; for the link-break agent, absent from the hybrid stack,
agents - hybrid). The p of the PSNR is Holm-corrected over the seven agents
alone and over the six removals; the link-break agent's p in the hybrid stack is
a single test. A cell that the 60 seeds do not all back prints as a dash.

Usage: make_tables_ablation.py
"""
import os
import sys
from decimal import ROUND_HALF_UP, Decimal

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import analyse_ablation as ab  # noqa: E402
import table_cells  # noqa: E402

SRC = os.path.join(HERE, '..', 'src')
AGENTS = (('P', 'Chemin', 'Path'), ('C', 'Congestion', 'Congestion'), ('A', 'Accès au canal', 'Channel access'),
          ('E', 'Rejet anticipé', 'Early discard'), ('D', 'Découverte', 'Discovery'), ('T', 'Puissance', 'Power'),
          ('B', 'Détection de rupture', 'Link-break detection'))
GROUPS = {'fr': ('Seul sur la pile à règles', 'Dans la pile hybride'),
          'en': ('Alone on the rule stack', 'In the hybrid stack')}
# No note under this table (the choice of 12 Nov 2026): PSNR and
# Decl. are defined in the metrics table (tab:metriques, Section 2.5), and the
# sign convention, the stack with the agent minus the stack with its rule,
# stands in the caption; the link-break row follows that convention.
HEAD = {'fr': ('Agent', 'PSNR (dB)', '$p$', 'Perte M1 (points)', 'Décl.'),
        'en': ('Agent', 'PSNR (dB)', '$p$', 'M1 loss (points)', 'Decl.')}
# Unequal widths, summing to the four columns of a group, so that the bold
# headers hold on two lines: "Perte M1" is 40.8 pt bold, "< 0,001" 33.6 pt,
# "PSNR" 27.8 pt and "Décl." 27.9 pt, one unit about 40 pt at the full text
# width; each column gets its widest line plus an equal share of the free
# width, so that the gaps between columns are equal (measured on the MDPI
# class, 11 and 12 Nov 2026).
GROUP = ''.join('>{\\hsize=%s\\hsize\\centering\\arraybackslash}X' % f for f in ('0.88', '1.03', '1.20', '0.89'))


def rounded(x, nd):
    # Half up, as the text rounds: 0.125 prints 0.13.
    return Decimal(repr(x)).quantize(Decimal(1).scaleb(-nd), rounding=ROUND_HALF_UP)


def signed(x, nd, lang):
    if x is None:
        return '--'
    d = rounded(x, nd)
    s = str(abs(d))
    s = s.replace('.', '{,}') if lang == 'fr' else s
    if d == 0:
        return s
    return ('+' if d > 0 else '$-$') + s


def pval(p, lang):
    if p is None:
        return '--'
    if p < 0.001:
        return '$< 0{,}001$' if lang == 'fr' else '$< 0.001$'
    s = str(rounded(p, 3))
    return s.replace('.', '{,}') if lang == 'fr' else s


def cell(fam, x, k):
    """Field k of agent x in a family (1 the mean, 5 Holm's p), None when absent."""
    return fam[x][k] if x in fam else None


def write(lang, fams):
    g1, g2 = GROUPS[lang]
    h = HEAD[lang]
    out = ['% generated by tools/make_tables_ablation.py from src/data/revision.tsv',
           table_cells.setup(lang),
           '\\begin{tabularx}{\\linewidth}{l%s}' % (GROUP * 2), '\\toprule',
           ' & \\multicolumn{4}{c}{\\textbf{%s}} & \\multicolumn{4}{c}{\\textbf{%s}} \\\\' % (g1, g2),
           '\\cmidrule(lr){2-5}\\cmidrule(lr){6-9}',
           ' & '.join('\\textbf{%s}' % x for x in (h[0],) + h[1:] * 2) + ' \\\\', '\\midrule']
    rows = []
    for x, fr, en in AGENTS:
        cells = []
        for side in (0, 1):
            psnr, m1, dec = (fams[m][side] for m in ('psnr', 'm1loss', 'declared'))
            cells += [signed(cell(psnr, x, 1), 2, lang), pval(cell(psnr, x, 5), lang),
                      signed(cell(m1, x, 1), 1, lang), signed(cell(dec, x, 1), 1, lang)]
        rows.append([fr if lang == 'fr' else en] + cells)
    # the numbers of each column aligned on the decimal marker
    rows = table_cells.align_rows(rows, lang, range(1, 9), pcols=(2, 6))
    for i, r in enumerate(rows):
        out.append(' & '.join(r) + ' \\\\')
        out.append('\\bottomrule' if i == len(rows) - 1 else '\\midrule')
    out.append('\\end{tabularx}')
    with open(os.path.join(SRC, 'tables', '%s_revision-ablation.tex' % lang), 'w') as f:
        f.write('\n'.join(out) + '\n')


def main():
    fams = {m: ab.effects(m) for m in ('psnr', 'm1loss', 'declared')}
    for lang in ('fr', 'en'):
        write(lang, fams)
    print('tables/{fr,en}_revision-ablation.tex')


if __name__ == '__main__':
    main()
