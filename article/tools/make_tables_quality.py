#!/usr/bin/env python3
"""Quality of the images and delay of the packets for the four stacks of study 09
(revision, experiment E0), from src/data/revision.tsv.

Writes src/tables/fr_revision-qualite.tex and src/tables/en_revision-qualite.tex:
one row per stack and GOP, the GOP written once over its four stacks as in the
comparative tables, means over the 60 simulations of a stack and a GOP (three
fires, twenty seeds each). Columns: PSNR, SSIM, usable images out of 12 (frames
of PSNR >= 28 dB), mean delay and mean of the per-simulation 95th percentile of
the delay of the received packets (ms), and the share of the received packets
that arrive after the capture of the next image (the deadline miss, %). The
definitions are those of tools/compile_revision.py. A simulation that received
no packet has no delay: AOMDV keeps 58 of its 60 simulations in those columns.

With --stats, prints the paired tests the text cites instead. Two stacks are
paired on (fire, realisation) within a GOP. Families for Holm's correction:
  per GOP   one comparison and one metric over the three GOPs, the article's
            rule of a comparison repeated across cells;
  pooled    each seed's difference averaged over the three GOPs (60 seeds),
            one comparison over the six metrics.
The 95 % interval uses stats.t_quantile(0.95, n - 1): that helper is two-sided.

Usage: make_tables_quality.py [--stats]
"""
import argparse
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', 'src')
sys.path.insert(0, os.path.normpath(os.path.join(HERE, '..', '..', 'experiments', 'metrics')))
import stats  # noqa: E402

ARMS = (('pq', 'AOMDV', 'AOMDV'), ('rules', 'Règles', 'Rules'),
        ('agents', 'Agents', 'Agents'), ('hybrid', 'Hybride', 'Hybrid'))
SPLITS = (('3M9D', '3-9'), ('6M6D', '6-6'), ('9M3D', '9-3'))
# metric, decimals, scale applied to the stored value
# the table keeps what the text of E0 reads: usable images, mean delay,
# missed deadlines; SSIM and the 95th percentile stay in the printed statistics only
METRICS = (('psnr', 2, 1.0), ('usable', 1, 1.0), ('delay_mean', 0, 1000.0), ('late', 2, 1.0))
HEAD = {'fr': ('GOP', 'Pile', 'PSNR (dB)', 'Images\\textsuperscript{1}', 'Délai moyen (ms)\\textsuperscript{2}', 'Échéance manquée (\\%)\\textsuperscript{3}'),
        'en': ('GOP', 'Stack', 'PSNR (dB)', 'Images\\textsuperscript{1}', 'Mean delay (ms)\\textsuperscript{2}', 'Missed deadline (\\%)\\textsuperscript{3}')}
PAIRS = (('hybrid', 'rules'), ('agents', 'rules'), ('hybrid', 'agents'), ('rules', 'pq'), ('hybrid', 'pq'))


def load():
    lines = [l for l in open(os.path.join(SRC, 'data', 'revision.tsv')) if not l.startswith('#')]
    cols = lines[0].rstrip('\n').split('\t')
    return [dict(zip(cols, l.rstrip('\n').split('\t'))) for l in lines[1:]]


ROWS = load()


def values(arm, metric, split):
    """{(fire, realisation): value} of one stack at one GOP, study 09's protocol."""
    scale = dict((m, s) for m, _, s in METRICS).get(metric, 1.0)
    return {(r['fire'], r['realisation']): scale * float(r[metric]) for r in ROWS
            if r['arm'] == arm and r['split'] == split and r['period'] == 'p9' and r['dist'] == '40'
            and r[metric] != ''}


def mean(x):
    x = list(x)
    return sum(x) / len(x)


def summary(v):
    """n, mean, standard deviation, half-width of the 95 % interval."""
    v = list(v)
    n, m = len(v), mean(v)
    s = math.sqrt(sum((x - m) ** 2 for x in v) / (n - 1))
    return n, m, s, stats.t_quantile(0.95, n - 1) * s / math.sqrt(n)


def paired(a, b):
    """Mean of a - b over the seeds both hold, its 95 % interval and the two-sided p."""
    d = [a[k] - b[k] for k in a if k in b]
    n, m, s, h = summary(d)
    p = stats.t_sf2(m / (s / math.sqrt(n)), n - 1) if s > 0 else 1.0
    return n, m, m - h, m + h, p


def num(x, nd, lang):
    s = '%.*f' % (nd, x)
    # Thousands: a thin space in French from four digits; in English a comma
    # from five digits only, as MDPI asks (make_tables_revision.py does the same).
    if nd == 0 and abs(x) >= 1000 and lang == 'fr':
        s = s[:-3] + '\\,' + s[-3:]
    elif nd == 0 and abs(x) >= 10000:
        s = s[:-3] + ',' + s[-3:]
    return s.replace('.', '{,}') if lang == 'fr' else s


def write(lang):
    out = ['% generated by tools/make_tables_quality.py from src/data/revision.tsv',
           '\\begin{tabularx}{\\linewidth}{lCCCCC}', '\\toprule',
           ' & '.join('\\textbf{%s}' % h for h in HEAD[lang]) + ' \\\\', '\\midrule']
    for i, (split, level) in enumerate(SPLITS):
        for k, (arm, fr, en) in enumerate(ARMS):
            first = '\\multirow[m]{%d}{*}{%s}' % (len(ARMS), level) if k == 0 else ''
            cells = [num(mean(values(arm, m, split).values()), nd, lang) for m, nd, _ in METRICS]
            out.append(' & '.join([first, (fr if lang == 'fr' else en) + ('\\textsuperscript{4}' if arm == 'pq' else '')] + cells) + ' \\\\')
            if k < len(ARMS) - 1:
                out.append('\\cmidrule{2-6}')
        out.append('\\bottomrule' if i == len(SPLITS) - 1 else '\\midrule')
    out.append('\\end{tabularx}')
    path = os.path.join(SRC, 'tables', '%s_revision-qualite.tex' % lang)
    with open(path, 'w') as f:
        f.write('\n'.join(out) + '\n')


def holm_print(title, tests):
    """tests: (label, n, mean, low, high, p). Holm within the list."""
    print(title)
    adj = stats.holm([(t[0], '', t[5]) for t in tests])
    for t, a in zip(tests, adj):
        print('  %-28s n=%2d  %+9.4f [%+9.4f, %+9.4f]  p=%.3g  Holm %.3g' % (t + (a[-1],)))


def over_splits(a, b, metric):
    """Each seed's difference averaged over the three GOPs, as one-sample data."""
    d = {}
    for split, _ in SPLITS:
        y = values(b, metric, split)
        for k, v in values(a, metric, split).items():
            if k in y:
                d.setdefault(k, []).append(v - y[k])
    d = {k: mean(v) for k, v in d.items() if len(v) == len(SPLITS)}
    return paired(d, {k: 0.0 for k in d})


def report():
    print('Means per stack and GOP: n, mean, sd, 95 % half-width, min, max (delays in ms)')
    for split, level in SPLITS:
        for arm, fr, _ in ARMS:
            parts = []
            for m, nd, _ in METRICS:
                v = list(values(arm, m, split).values())
                n, mu, s, h = summary(v)
                parts.append('%s n=%d %.4f sd %.4f +-%.4f [%.3f, %.3f]' % (m, n, mu, s, h, min(v), max(v)))
            print('  %s %-7s ' % (level, fr) + ' | '.join(parts))

    print('\nUsable images: share of the 12 frames, and simulations with no usable frame')
    for split, level in SPLITS:
        for arm, fr, _ in ARMS:
            v = list(values(arm, 'usable', split).values())
            print('  %s %-7s %.1f %% of frames, %d of %d simulations with none'
                  % (level, fr, 100 * mean(v) / 12, sum(1 for x in v if x == 0), len(v)))

    print('\nLargest per-simulation 95th percentile of the delay (ms), over the three GOPs')
    for arm, fr, _ in ARMS:
        v = [x for split, _ in SPLITS for x in values(arm, 'delay_p95', split).values()]
        w = [x for split, _ in SPLITS for x in values(arm, 'late', split).values()]
        print('  %-7s max P95 %.0f ms over %d simulations; max missed deadlines %.2f %%' % (fr, max(v), len(v), max(w)))

    for metric, _, _ in METRICS:
        print('\n== %s' % metric)
        for a, b in PAIRS:
            holm_print('  %s - %s, per GOP (Holm over the three GOPs)' % (a, b),
                       [(level,) + paired(values(a, metric, split), values(b, metric, split)) for split, level in SPLITS])

    print('\n== usable images at the bounds of the fair class, 25 and 31 dB: means, then per GOP (Holm over the three GOPs)')
    for m in ('usable25', 'usable31'):
        for split, level in SPLITS:
            print('  %s %s: ' % (m, level) + ', '.join('%s %.2f' % (fr, mean(list(values(arm, m, split).values())))
                                                for arm, fr, _ in ARMS))
        for a, b in (('hybrid', 'rules'), ('hybrid', 'agents')):
            holm_print('  %s %s - %s' % (m, a, b),
                       [(level,) + paired(values(a, m, split), values(b, m, split)) for split, level in SPLITS])

    print('\n== pooled: each seed averaged over the three GOPs (Holm over the six metrics of a comparison)')
    for a, b in PAIRS:
        holm_print('  %s - %s' % (a, b), [(m,) + over_splits(a, b, m) for m, _, _ in METRICS])


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--stats', action='store_true', help='print the paired tests instead of writing the tables')
    if ap.parse_args().stats:
        report()
        return
    for lang in ('fr', 'en'):
        write(lang)
    print('tables/{fr,en}_revision-qualite.tex')


if __name__ == '__main__':
    main()
