#!/usr/bin/env python3
"""LaTeX table of the load sweep of the revision (study 10, tranche T3, experiment E5, load series),
French and English, from src/data/revision.tsv. One row per alarm period T, at
GOP 9-3: the rule stack's packet loss, the PSNR of the four stacks over the 60
seeds, then the per-seed difference hybrid - rules for the PSNR, with its p
Holm-corrected over the five periods, and for the usable images (PSNR >= 28 dB,
out of 12). T = 9 s is study 09. A cell that the 60 seeds do not all back prints
as a dash.

Usage: python3 tools/make_tables_charge.py [OUT_DIR]   (default: src/tables)
"""
import math
import os
import sys
from decimal import ROUND_HALF_UP, Decimal

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.normpath(os.path.join(HERE, '..', '..', 'experiments', 'metrics')))
import stats  # noqa: E402
sys.path.insert(0, HERE)
import table_cells  # noqa: E402

DATA = os.path.join(HERE, '..', 'src', 'data', 'revision.tsv')
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, '..', 'src', 'tables')
PERIODS = (('p7', '7'), ('p9', '9'), ('p12', '12'), ('p18', '18'), ('p30', '30'))
# The four stacks in the article's order; the gap group named as in the
# other tables of differences (Hybrid - Rules); note 1 says whose loss it is.
STACKS = ('pq', 'rules', 'agents', 'hybrid')
GROUPS = {'fr': ('PSNR (dB)', 'Hybride $-$ Règles'),
          'en': ('PSNR (dB)', 'Hybrid $-$ Rules')}
# The loss is the rule stack's: the stack heads its column on the row of the
# groups, as the stacks' names head the PSNR; Images is defined in the metrics
# table (tab:metriques): no note under this table (12 Nov 2026).
LOSS_STACK = {'fr': 'Règles', 'en': 'Rules'}
HEAD = {'fr': ('$T$ (s)', 'Perte (\\%)', 'AOMDV', 'Règles', 'Agents', 'Hybride', 'PSNR (dB)', '$p$', 'Images'),
        'en': ('$T$ (s)', 'Loss (\\%)', 'AOMDV', 'Rules', 'Agents', 'Hybrid', 'PSNR (dB)', '$p$', 'Images')}
# The period centered as a value, then each X column with its header on one
# line plus an equal share of the free width (measured on the MDPI class,
# 12 Nov 2026).
COLS = ''.join('>{\\hsize=%s\\hsize\\centering\\arraybackslash}X' % w
               for w in ('0.65', '1.20', '1.12', '0.87', '0.90', '1.04', '1.28', '0.93', '1.01'))

lines = [l for l in open(DATA) if not l.startswith('#')]
cols = lines[0].rstrip('\n').split('\t')
REV = [dict(zip(cols, l.rstrip('\n').split('\t'))) for l in lines[1:]]


def values(arm, period, metric):
    return {(r['fire'], r['realisation']): float(r[metric]) for r in REV
            if r['arm'] == arm and r['split'] == '9M3D' and r['dist'] == '40' and r['period'] == period and r[metric] != ''}


def mean(arm, period, metric):
    v = values(arm, period, metric)
    return sum(v.values()) / len(v) if len(v) == 60 else None


def paired(a, b):
    k = [x for x in a if x in b]
    if len(k) != 60:
        return None, None
    d = [a[x] - b[x] for x in k]
    n, m = len(d), sum(d) / len(d)
    s = math.sqrt(sum((x - m) ** 2 for x in d) / (n - 1))
    return m, stats.t_sf2(m / (s / math.sqrt(n)), n - 1) if s > 0 else 1.0


def holm(ps):
    o = sorted(range(len(ps)), key=lambda i: ps[i])
    out, run = [None] * len(ps), 0.0
    for j, i in enumerate(o):
        run = max(run, min(1.0, (len(ps) - j) * ps[i]))
        out[i] = run
    return out


def rounded(x, nd):
    # Half up, as the text rounds: 0.125 prints 0.13.
    return Decimal(repr(x)).quantize(Decimal(1).scaleb(-nd), rounding=ROUND_HALF_UP)


def plain(x, nd, lang):
    if x is None:
        return '--'
    s = str(rounded(x, nd))
    return s.replace('.', '{,}') if lang == 'fr' else s


def signed(x, nd, lang):
    if x is None:
        return '--'
    d = rounded(x, nd)
    s = str(abs(d))
    s = s.replace('.', '{,}') if lang == 'fr' else s
    return s if d == 0 else ('+' if d > 0 else '$-$') + s


def pval(p, lang):
    if p is None:
        return '--'
    if p < 0.001:
        return '$< 0{,}001$' if lang == 'fr' else '$< 0.001$'
    s = str(rounded(p, 3))
    return s.replace('.', '{,}') if lang == 'fr' else s


def rows():
    psnr = [paired(values('hybrid', p, 'psnr'), values('rules', p, 'psnr')) for p, _ in PERIODS]
    img = [paired(values('hybrid', p, 'usable'), values('rules', p, 'usable')) for p, _ in PERIODS]
    hp = holm([x[1] for x in psnr]) if all(x[1] is not None for x in psnr) else [None] * len(PERIODS)
    return psnr, img, hp


def write(lang):
    psnr, img, hp = rows()
    g1, g2 = GROUPS[lang]
    h = HEAD[lang]
    out = ['% generated by tools/make_tables_charge.py from src/data/revision.tsv',
           table_cells.setup(lang),
           '\\begin{tabularx}{\\linewidth}{%s}' % COLS, '\\toprule',
           ' & \\textbf{%s} & \\multicolumn{4}{c}{\\textbf{%s}} & \\multicolumn{3}{c}{\\textbf{%s}} \\\\' % (LOSS_STACK[lang], g1, g2),
           '\\cmidrule(lr){2-2}\\cmidrule(lr){3-6}\\cmidrule(lr){7-9}',
           ' & '.join('\\textbf{%s}' % x for x in h) + ' \\\\', '\\midrule']
    body = []
    for i, (p, t) in enumerate(PERIODS):
        cells = [t, plain(mean('rules', p, 'loss'), 1, lang)]
        cells += [plain(mean(s, p, 'psnr'), 2, lang) for s in STACKS]
        cells += [signed(psnr[i][0], 2, lang), pval(hp[i], lang), signed(img[i][0], 1, lang)]
        body.append(cells)
    # the period and every number aligned on the decimal marker
    body = table_cells.align_rows(body, lang, pcols=(7,))
    for i, cells in enumerate(body):
        out.append(' & '.join(cells) + ' \\\\')
        out.append('\\bottomrule' if i == len(body) - 1 else '\\midrule')
    out.append('\\end{tabularx}')
    path = os.path.join(OUT, '%s_revision-charge.tex' % lang)
    with open(path, 'w') as f:
        f.write('\n'.join(out) + '\n')
    return path


def main():
    for lang in ('fr', 'en'):
        print(write(lang))


if __name__ == '__main__':
    main()
